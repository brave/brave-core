def _source_body(name: str) -> str:
    """The upstream contents of a fake Chromium source.

    Line `PATCHED_LINE` carries the symbol brave rewrites; every other line is
    filler that gives patches enough context to be interesting.
    """
    lines = [
        f'// {name} line {number}' for number in range(1, SOURCE_LINES + 1)
    ]
    lines[PATCHED_LINE - 1] = f'  {UPSTREAM_SYMBOL} thing;  // {name}'
    return ''.join(f'{line}\n' for line in lines)


def log_link(from_version: str, to_version: str) -> str:
    """The Googlesource log link brockit prints for a version range."""
    return ('https://chromium.googlesource.com/chromium/src/+log/'
            f'{from_version}..{to_version}?pretty=fuller&n=10000')


def _with_line(body: str, line: int, text: str) -> str:
    """`body` with `line` (1-based) replaced by `text`."""
    lines = body.splitlines(keepends=True)
    lines[line - 1] = f'{text}\n'
    return ''.join(lines)


@dataclass(frozen=True)
class LiftRun:
    """The outcome of one `brockit lift` invocation."""

    # The process exit code `main()` produced (2 for a usage error).
    exit_code: int

    # Everything the run printed to the rich console.
    output: str

    # Everything the run wrote to stderr (argparse usage errors).
    stderr: str


class _AdvancingClock:
    """A `datetime` stand-in whose `now()` moves a minute forward each call.

    The pinslist timestamp is stamped in whole seconds, and the lift treats a
    stamp that did not change as a failure. Two lifts inside the same second
    only ever happen in a test, and this keeps them apart.
    """

    def __init__(self) -> None:
        self._elapsed = timedelta()

    def now(self) -> datetime:
        """The current time, a minute later on every call."""
        self._elapsed += timedelta(minutes=1)
        return datetime.now() + self._elapsed

    @staticmethod
    def fromtimestamp(timestamp: float) -> datetime:
        """Delegates to the real `datetime`."""
        return datetime.fromtimestamp(timestamp)


class _Upstream:
    """Commits Chromium-side changes while building a release.

    Handed out by `LiftEnvironment.upstream_release`. Each method commits on its
    own so that every change has a culprit commit brockit can attribute a
    deleted or renamed source to.
    """

    def __init__(self, repo: FakeChromiumRepo) -> None:
        self._repo = repo

    def _repo_path(self, repo: str) -> Path:
        return self._repo.chromium / repo

    def edit(self,
             source: str,
             *,
             line: int,
             text: str,
             repo: str = '') -> str:
        """Rewrites one line of an existing source and commits it."""
        repo_path = self._repo_path(repo)
        body = (repo_path / source).read_bytes().decode('utf-8')
        self._repo.write_and_stage_file(source, _with_line(body, line, text),
                                        repo_path)
        return self._repo.commit(f'Upstream change to {source}', repo_path)

    def write(self, source: str, content: str, repo: str = '') -> str:
        """Writes a source wholesale (new or existing) and commits it."""
        repo_path = self._repo_path(repo)
        self._repo.write_and_stage_file(source, content, repo_path)
        return self._repo.commit(f'Upstream change to {source}', repo_path)

    def delete(self, source: str, repo: str = '') -> str:
        """Deletes a source and commits the deletion."""
        repo_path = self._repo_path(repo)
        self._repo.delete_file(source, repo_path)
        return self._repo.commit(f'Remove {source}', repo_path)

    def rename(self, source: str, new_source: str, repo: str = '') -> str:
        """Renames a source and commits the rename."""
        repo_path = self._repo_path(repo)
        (repo_path / new_source).parent.mkdir(parents=True, exist_ok=True)
        # pylint: disable=protected-access
        self._repo._run_git_command(['mv', source, new_source], repo_path)
        return self._repo.commit(f'Rename {source} to {new_source}', repo_path)


class LiftEnvironment:
    """A sandbox for driving `brockit lift` end to end.

    The fixture starts from the state a lift starts from in practice:

    * `src/` is synced to `BASE_VERSION` (a real tag) with brave's patches
      applied to the working tree, and the `v8` dependency alongside it,
    * brave is on the `cr135` branch tracking `origin/master`, holding
      `package.json` at `BASE_VERSION`, the pinslist timestamp file, the l10n
      files, the `gnrt` output, and the patch files for every patched source.

    From there a test describes what Chromium did in the meantime through
    `upstream_release`, and runs the command with `run_lift`.
    """

    def __init__(self,
                 *,
                 branch: str = MAJOR_BRANCH,
                 upstream_files: dict[str, str] | None = None) -> None:
        # Declared up front so `cleanup` can run after a half-built fixture:
        # `FakeChromiumRepo.setup` changes the current directory, so a fixture
        # that fails half way through has to be torn down or every test after
        # it runs from a directory that no longer exists.
        self.repo = FakeChromiumRepo()
        self.baseline_commit = ''
        self.console: ConsoleCapture | None = None
        self.terminal: FakeTerminal | None = None
        self.gh = FakeGh()
        self._vscode_patcher = None
        self.vscode = None
        self._clock_patcher = None
        self._saved_upgrade_file = brockit.VERSION_UPGRADE_FILE

        try:
            self._build(branch, upstream_files or {})
        except Exception:
            self.cleanup()
            raise

    def _build(self, branch: str, upstream_files: dict[str, str]) -> None:
        """Builds the checkout and installs the doubles."""
        self.repo.setup()
        self.repo.add_dep(V8)

        self._build_chromium_baseline(upstream_files)
        self._build_brave_baseline(branch)

        # The brave commit the fixture leaves behind, so a test can ask for the
        # commits a lift added on top of it.
        self.baseline_commit = self.head()

        # Doubles: git stays real, and everything else is emulated or captured.
        self.console = ConsoleCapture().install()
        self.terminal = FakeTerminal(self.repo, gh=self.gh).install()

        # Files needing attention are handed to the editor over the VS Code IPC
        # socket, which must never be talked to from a test.
        self._vscode_patcher = patch.object(brockit, 'VsCodeIpcConnection')
        self.vscode = self._vscode_patcher.start()

        # Successive lifts in one test would otherwise stamp the pinslist file
        # with the same second.
        self._clock_patcher = patch.object(brockit, 'datetime',
                                           _AdvancingClock())
        self._clock_patcher.start()

        # The continuation file is resolved against the brave root, which in the
        # fake checkout is the fake brave repo. It is reset here rather than
        # relied upon so this fixture is unaffected by any other test module
        # having overwritten the module global.
        brockit.VERSION_UPGRADE_FILE = (brockit.repository.brave.root /
                                        VERSION_UPGRADE_NAME)

    def cleanup(self) -> None:
        """Uninstalls every double and removes the fake checkout."""
        brockit.VERSION_UPGRADE_FILE = self._saved_upgrade_file
        if self._clock_patcher is not None:
            self._clock_patcher.stop()
            self._clock_patcher = None
        if self._vscode_patcher is not None:
            self._vscode_patcher.stop()
            self._vscode_patcher = None
        if self.terminal is not None:
            self.terminal.uninstall()
            self.terminal = None
        if self.console is not None:
            self.console.uninstall()
            self.console = None
        self.repo.cleanup()

    # -- fixture ------------------------------------------------------------

    def _build_chromium_baseline(self, upstream_files: dict[str, str]) -> None:
        """Commits the patched sources and tags `BASE_VERSION`.

        Args:
            upstream_files: Extra Chromium files (path to contents) to commit
                into the base release, for tests that need Chromium to carry
                something specific -- e.g. a toolchain pin.
        """
        for source in (FOO, BAR):
            self.repo.write_and_stage_file(source, _source_body(source),
                                           self.repo.chromium)
        for path, contents in upstream_files.items():
            self.repo.write_and_stage_file(path, contents, self.repo.chromium)
        self.repo.commit('Add sources', self.repo.chromium)
        self.repo.write_and_stage_file(BAZ, _source_body(BAZ),
                                       self.repo.chromium / V8)
        self.repo.commit('Add v8 sources', self.repo.chromium / V8)
        self.repo.add_tag(BASE_VERSION)

    def _build_brave_baseline(self, branch: str) -> None:
        """Sets brave up on `branch`, with patches for every patched source."""
        brave = self.repo.brave
        self.repo.update_brave_version(BASE_VERSION)

        # The real pinslist file is used so the block brockit rewrites is the
        # one that ships.
        pinslist = Path(brockit.PINSLIST_TIMESTAMP_FILE)
        (brave / pinslist).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(
            Path(__file__).resolve().parents[2] / pinslist, brave / pinslist)
        # `.patchinfo` files are generated by the patching machinery and never
        # committed, as in brave-core itself.
        self.repo.write_file('.gitignore', 'patches/**/*.patchinfo\n', brave)
        for relative_path in L10N_FILES:
            self.repo.write_file(relative_path, f'<!-- {relative_path} -->\n',
                                 brave)
        self.repo.write_file(GNRT_FILE, '# generated by gnrt\n', brave)
        self.git('add', '--all')
        self.repo.commit('Add brave files', brave)

        self.repo.create_brave_remote()
        # The remote is a normal checkout with `master` checked out, so it has
        # to be told to accept pushes to it.
        self.git('config',
                 'receive.denyCurrentBranch',
                 'ignore',
                 repo=self.repo.remote / 'brave')
        # The freshly-initialised remote carries an unrelated initial commit, so
        # the push is forced to make `origin/master` this repo's history.
        self.git('push', '--force', 'origin', f'HEAD:{DEFAULT_BRANCH}')
        self.git('checkout', '-b', branch)
        self.git('branch', f'--set-upstream-to=origin/{DEFAULT_BRANCH}')

        self.apply_brave_changes()
        self.repo.commit_patches('Add patches')

    def apply_brave_changes(self) -> None:
        """Applies brave's own change to every patched source in the tree.

        This is the modification the patch files capture: the upstream symbol on
        the patched line rewritten to brave's.
        """
        for source, repo in ((FOO, ''), (BAR, ''), (BAZ, V8)):
            repo_path = self.repo.chromium / repo
            body = (repo_path / source).read_bytes().decode('utf-8')
            self.repo.write_file(source,
                                 body.replace(UPSTREAM_SYMBOL, BRAVE_SYMBOL),
                                 repo_path)

    @contextmanager
    def upstream_release(self, version: str):
        """Builds the Chromium release `version` on top of the current one.

        Inside the block the yielded `_Upstream` commits changes one at a time.
        Leaving the block tags the release and puts the checkout back where a
        lift starts from: synced to the version in brave's `package.json`, with
        brave's patches applied.
        """
        self.repo.sync_chromium()
        yield _Upstream(self.repo)
        self.repo.add_tag(version)
        self.repo.sync_chromium()
        self.repo.run_apply_patches()

    # -- running ------------------------------------------------------------

    def run_lift(self, *args: str) -> LiftRun:
        """Runs `brockit lift` with `args`, as the command line would.

        A usage error (argparse calling `sys.exit`) is reported as exit code 2
        rather than propagating, so those runs read like any other.
        """
        mark = self.console.mark()
        stderr = io.StringIO()
        with patch.object(sys, 'argv', ['brockit.py', 'lift', *args]):
            with redirect_stderr(stderr):
                try:
                    exit_code = brockit.main()
                except SystemExit as e:
                    exit_code = e.code
        return LiftRun(exit_code=exit_code,
                       output=self.console.since(mark),
                       stderr=stderr.getvalue())

    # -- inspection ---------------------------------------------------------

    def git(self, *args: str, repo: Path | None = None) -> str:
        """Runs a git command in the fake brave repo (or `repo`)."""
        # pylint: disable=protected-access
        return self.repo._run_git_command(list(args), repo or self.repo.brave)

    def head(self) -> str:
        """The brave `HEAD` hash."""
        return self.git('rev-parse', 'HEAD')

    def subjects(self, since: str | None = None) -> list[str]:
        """Subjects of the brave commits after `since`, oldest first.

        Defaults to every commit the fixture did not create.
        """
        log = self.git('log', '--reverse', '--pretty=%s',
                       f'{since or self.baseline_commit}..HEAD')
        return log.splitlines()

    def commit_for(self, subject: str) -> str:
        """The hash of the most recent brave commit with `subject`.

        Empty when the branch has no such commit.
        """
        return self.git('log', '-1', '--format=%H', '--fixed-strings',
                        f'--grep={subject}')

    def files_in(self, commit: str = 'HEAD') -> list[str]:
        """The paths a brave commit touches."""
        return self.git('show', '--name-only', '--pretty=format:',
                        commit).split()

    def source_path(self, source: str, repo: str = '') -> str:
        """The path brockit prints for a Chromium source.

        brockit expresses Chromium paths relative to the directory it was
        invoked from, so the expectation is computed the same way rather than
        being hardcoded.
        """
        return os.path.relpath(self.repo.chromium / repo / source, Path.cwd())

    def brave_path(self, relative_path: str) -> str:
        """The path brockit prints for a file in brave, e.g. a plaster file."""
        return os.path.relpath(self.repo.brave / relative_path, Path.cwd())

    def read_source(self, source: str, repo: str = '') -> str:
        """The working-tree contents of a Chromium source."""
        return (self.repo.chromium / repo /
                source).read_bytes().decode('utf-8')

    def upstream_source(self, source: str, repo: str = '') -> str:
        """The contents of a Chromium source at the synced commit."""
        return self.git('show',
                        f'HEAD:{source}',
                        repo=self.repo.chromium / repo)

    def resolve_conflict(self,
                         source: str,
                         repo: str = '',
                         symbol: str = BRAVE_SYMBOL) -> None:
        """Resolves a conflicted source the way the user is expected to.

        Rewrites the file as the upstream version of it carrying brave's change,
        which is what editing the conflict markers out by hand amounts to.

        Args:
            source: The Chromium source to resolve.
            repo: The repository the source belongs to.
            symbol: The spelling brave's change gives the upstream symbol. Pass
                it when a dev-cycle commit in the branch has moved it on.
        """
        body = self.upstream_source(source,
                                    repo).replace(UPSTREAM_SYMBOL, symbol)
        self.repo.write_file(source, body, self.repo.chromium / repo)

    def continuation(self, target: str) -> brockit.ContinuationFile:
        """The continuation file left in the tree for the `target` lift."""
        return brockit.ContinuationFile.load(
            target_version=brockit.Version(target))

    def has_continuation(self) -> bool:
        """Whether a continuation file is left in the tree."""
        return brockit.VERSION_UPGRADE_FILE.exists()

    def vscode_files(self) -> list[str]:
        """The files handed to the editor, as posix strings."""
        calls = self.vscode.return_value.open_file.call_args_list
        return [Path(f).as_posix() for call in calls for f in call.args[0]]

    def write_plaster(self, relative_path: str, body: str) -> None:
        """Writes a plaster file into brave's `rewrite/` directory."""
        self.repo.write_file(relative_path, body, self.repo.brave)

    def add_plaster_for_foo(self, body: str = FOO_PLASTER_BODY) -> None:
        """Makes `FOO`'s patch plaster-managed, and commits that.

        The patch is regenerated by plaster itself rather than by
        `update_patches`, which is the invariant plaster-managed patches hold in
        brave-core: the patch on disk is exactly what a plaster run produces.
        """
        self.write_plaster(FOO_PLASTER, body)
        plaster.PlasterFile(plaster.PLASTER_FILES_PATH / f'{FOO}.yaml').apply()
        self.git('add', '--all', 'rewrite', 'patches')
        self.repo.commit('Add plaster for foo.cc', self.repo.brave)

    def reapply_plaster_for_foo(self, body: str) -> None:
        """Rewrites `FOO`'s plaster and reapplies it, as the user would.

        This is the fix for a plaster that stopped matching its source: the
        plaster is corrected and re-run so the source and the patch are
        regenerated from it.
        """
        self.write_plaster(FOO_PLASTER, body)
        plaster.PlasterFile(plaster.PLASTER_FILES_PATH / f'{FOO}.yaml').apply()

    def break_patch(self, patch_path: str) -> None:
        """Rewrites a committed patch so that nothing can apply it.

        The blob hashes are replaced with ones the repository does not have, and
        the first context line is mangled, so neither a plain apply nor a 3-way
        merge has anything to work with -- which is what brockit reports as a
        broken patch.
        """
        path = self.repo.brave / patch_path
        body = path.read_bytes().decode('utf-8')
        body = re.sub(r'index [0-9a-f]+\.\.[0-9a-f]+',
                      f'index {"1" * 40}..{"2" * 40}', body)
        body = re.sub(r'(?m)^ .*$',
                      ' // a line that is not in the source',
                      body,
                      count=1)
        path.write_text(body, encoding='utf-8', newline='')
        self.git('add', patch_path)
        self.repo.commit(f'Break {patch_path}', self.repo.brave)

    def stage_file(self, relative_path: str, content: str) -> None:
        """Leaves a staged change in brave, as an interrupted edit would."""
        self.repo.write_and_stage_file(relative_path, content, self.repo.brave)

    def commit_patch_changes(self, message: str) -> str:
        """Commits the patch files as they stand, as the user is asked to.

        This is what brockit expects for patch additions and deletions: the user
        regenerates the patches and commits them with a message of their own.
        """
        return self.repo.commit_patches(message)


class LiftTestCase(unittest.TestCase):
    """Base for the lift tests: one sandbox per test, plus assertions."""

    # The branch the fake brave repo is put on. Named after the major being
    # lifted to, which is what a major lift requires.
    BRANCH = MAJOR_BRANCH

    # Extra Chromium files the base release carries, for tests that need
    # upstream to hold something specific.
    UPSTREAM_FILES: dict[str, str] = {}

    def setUp(self) -> None:
        self.env = LiftEnvironment(branch=self.BRANCH,
                                   upstream_files=self.UPSTREAM_FILES)
        self.addCleanup(self.env.cleanup)

    # -- assertions ---------------------------------------------------------

    @staticmethod
    def normalized(run: LiftRun) -> str:
        """The run's output with commit hashes replaced by a placeholder."""
        return re.sub(r'\b[0-9a-f]{7,40}\b', '<hash>', run.output)

    def assert_output_has(self, run: LiftRun, *lines: str) -> None:
        """Asserts each of `lines` appears in the run's output."""
        for line in lines:
            self.assertIn(line, run.output,
                          f'missing from the output:\n{run.output}')

    def assert_output_lacks(self, run: LiftRun, *lines: str) -> None:
        """Asserts none of `lines` appears in the run's output."""
        for line in lines:
            self.assertNotIn(line, run.output,
                             f'unexpectedly in the output:\n{run.output}')

    def assert_succeeded(self, run: LiftRun) -> None:
        """Asserts the run reported success and was framed by the banners."""
        self.assertEqual(run.exit_code, 0, f'run failed:\n{run.output}')
        self.assert_output_has(run, '🚀 Brockit!', '💥 Done!')

    def assert_failed(self, run: LiftRun, *lines: str) -> None:
        """Asserts the run failed, printing `lines`, and never said it was
        done."""
        self.assertEqual(run.exit_code, 1, f'run succeeded:\n{run.output}')
        self.assert_output_has(run, *lines)
        self.assert_output_lacks(run, '💥 Done!')

    def assert_commit_subjects(self, expected: list[str]) -> None:
        """Asserts the commits added on top of the fixture."""
        self.assertEqual(self.env.subjects(), expected)


class LiftCleanRunTest(LiftTestCase):
    """A lift where every patch still applies."""

