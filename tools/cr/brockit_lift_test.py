"""End-to-end tests for `brockit.py lift`.

Where `brockit_test.py` exercises the individual pieces of the lift in
isolation, these tests drive the command the way a user does: `brockit.main()`
is called with an argument list, and everything from argument parsing to the
exit code, the commits left in the branch, and the output printed to the
terminal is asserted on.

The sandbox is genuine. `LiftEnvironment` stands up a fake Chromium checkout
with brave inside it (`FakeChromiumRepo`), real Chromium release tags, real
patch files generated by real `git diff`, and a branch with a real upstream.
Every git command the lift runs -- the version commit, the `--3way` applies,
the fixups, the resets -- runs against that checkout for real. Only the things
a fake checkout cannot serve are emulated (see `test/fake_terminal.py`): the
`npm run` build commands, which are emulated over the same fake repositories,
the `gh` CLI, and the `vpython3` helper scripts.

Consequently a patch conflicts here because git could not merge it, a patch is
reported as deleted because its source is really gone from the tree at the
target tag, and a rename is reported because git's rename detection found it.
"""

