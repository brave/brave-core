import Foundation

/// A named collection of tabs. Membership is owned by `TabManager`, which maps tab ids to a group.
struct TabGroup: Identifiable, Hashable {
  let id: UUID
  var title: String

  // A group is the same group when renamed
  static func == (lhs: Self, rhs: Self) -> Bool {
    lhs.id == rhs.id
  }

  func hash(into hasher: inout Hasher) {
    hasher.combine(id)
  }
}
