"""Refresh checked-in notices; never downloads anything during an app build.

The inventory deliberately includes the entire pinned IPtProxy module manifest,
including tooling and transports not exposed by Brave. A missing license fails
generation rather than silently omitting a dependency. Review the resulting diff
and the upstream license terms when updating either binary dependency.
"""

import concurrent.futures
import hashlib
import io
from pathlib import Path
import re
import urllib.request
import zipfile

from generate_credit_entries import write_entries

IPTPROXY = '46552b8422a200e3e69aa3686b6278be945138a5'  # 5.7.0
DNSTT = 'f1b9b97a269f83bad41d2ceef291b4d2c161cd11'
GO = 'go1.27.1'  # Verified in the pinned ios-arm64 IPtProxy binary.
RAW = 'https://raw.githubusercontent.com'


def download(url):
    with urllib.request.urlopen(url, timeout=60) as response:
        return response.read()


def is_notice(path):
    return re.fullmatch(
        r'(licen[cs]e|copying|copyright|notice|patents)([._-].*)?',
        Path(path).name, re.IGNORECASE
    ) is not None


def archive_notices(module, version):
    # Go module proxy encodes uppercase letters as ! followed by lowercase.
    escaped = re.sub(r'[A-Z]', lambda m: '!' + m[0].lower(), module)
    if module == 'www.bamsoftware.com/git/dnstt.git':
        url = f'https://codeload.github.com/tladesignz/dnstt/zip/{DNSTT}'
    else:
        url = f'https://proxy.golang.org/{escaped}/@v/{version}.zip'
    data = download(url)
    archive = zipfile.ZipFile(io.BytesIO(data))
    notices = []
    for name in sorted(archive.namelist()):
        if not name.endswith('/') and is_notice(name):
            text = archive.read(name).decode('utf-8-sig')
            notices.append(f'File: {name}\n\n{text.rstrip()}\n')
    if not notices:
        raise ValueError(f'No license found for {module}@{version}')
    return (f'{module} {version}\nSource archive: {url}\n'
            f'Archive SHA-256: {hashlib.sha256(data).hexdigest()}\n\n'
            + '\n'.join(notices))


def generate():
    base = f'{RAW}/tladesignz/IPtProxy/{IPTPROXY}'
    manifest = download(f'{base}/IPtProxy.go/go.mod').decode('utf-8')
    modules = re.findall(r'^\s*([^\s]+) (v[^\s]+)(?: // indirect)?$',
                         manifest, re.MULTILINE)
    if not modules or len({name for name, _ in modules}) != len(modules):
        raise ValueError('Invalid or empty module inventory')
    entries = [
        f'IPtProxy 5.7.0\nSource: {base}\n\n'
        + download(f'{base}/LICENSE').decode('utf-8'),
        f'Go runtime {GO}\nSource: https://github.com/golang/go/tree/{GO}\n\n'
        + '\n'.join(download(f'{RAW}/golang/go/{GO}/{name}').decode('utf-8')
                    for name in ('LICENSE', 'PATENTS')),
    ]
    with concurrent.futures.ThreadPoolExecutor(max_workers=8) as executor:
        entries += list(executor.map(lambda item: archive_notices(*item),
                                     sorted(modules)))
    header = (
        'IPtProxy and bundled transport dependency notices\n'
        'Generated by ios/tor/credits/generate_transport_notices.py.\n'
        f'Module inventory: {base}/IPtProxy.go/go.mod\n'
        'Includes the complete pinned module manifest, not only active transports.\n'
    )
    text = header + '\n' + ('\n' + '=' * 72 + '\n\n').join(entries)
    return '\n'.join(line.rstrip() for line in text.splitlines()) + '\n'


if __name__ == '__main__':
    output = Path(__file__).resolve().parents[1] / (
        'Sources/BraveTorUI/Resources/TransportNotices.txt')
    # Generate fully before replacing the existing notice inventory.
    output.write_text(generate(), encoding='utf-8')
    write_entries(Path(__file__).resolve().parents[1])
    print(f'Updated {output}')
