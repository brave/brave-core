"""
Generates a replacement root_cert_list_generated.h from upstream
root_stores.json *plus the Chrome Root Store*, so roots missing from the stale
upstream table count as known on platforms that depend on this for such checks.

Most platforms directly interrogate the Chrome Root Store for "is known" checks.
Only iOS, CRONET, and Android Webview rely on the root cert list. Brave doesn't
ship CRONET or Android Webview, so this is only pertinant for iOS.

Upstream has seemingly given up on cert pinning in iOS, but Brave depends on it
and will be keeping it enabled via `chrome_key_pinning_supported` in
`build/args/ios_defaults.gni`. We shouldn't expect much help from upstream.

If this change is not made, then certificates which *should* be rejected due to
certificate pinning failures may be accepted under the incorrect conclusion that
the certificate is part of a private trust chain. This is due to the upstream
`root_stores.json` being out of date, last updated in 2022. In fact, several
*public* trust anchors known to the Chrome Root Store are missing from
`root_stores.json`.

Again, this is only a gap for platforms that rely on `root_stores.json`, rather
than interrogating the Chrome Root Store directly. Essentially iOS, only.

Note that the reasoning for allowing pin failures for private trust anchors is
described here:

    > https://chromium.googlesource.com/chromium/src/+/HEAD/docs/security/faq.md

    ## How does key pinning interact with local proxies and filters?

    Chrome does not perform pin validation when the certificate chain chains
    up to a private trust anchor. A key result of this policy is that private
    trust anchors can be used to proxy (or MITM) connections, even to pinned
    sites. “Data loss prevention” appliances, firewalls, content filters, and
    malware can use this feature to defeat the protections of key pinning.

IMPORTANT: Changing this file? Run
brave/net/cert/generate_root_cert_list_test.py after doing so. The test is not
automatically run, but is useful as a check on revisions to this file.
"""

import argparse
import base64
import hashlib
import json
import re
import sys
from pathlib import Path

# Keeps CRS-derived IDs clear of the upstream NetTrustAnchors range.
CRS_HISTOGRAM_ID_BASE = 10000
MAX_HISTOGRAM_ID = (1 << 14) - 1  # int16_t histogram_id : 15

HEADER = """\
// Copyright (c) 2026 The Brave Authors. All rights reserved.
// This Source Code Form is subject to the terms of the Mozilla Public
// License, v. 2.0. If a copy of the MPL was not distributed with this file,
// You can obtain one at https://mozilla.org/MPL/2.0/.
//
// Generated by brave/net/cert/generate_root_cert_list.py. DO NOT EDIT!

#ifndef BRAVE_NET_CERT_ROOT_CERT_LIST_GENERATED_H_
#define BRAVE_NET_CERT_ROOT_CERT_LIST_GENERATED_H_

#include <stdint.h>

namespace net {

namespace {

// The list of known trust anchors, sorted by sha256_spki_hash.
const struct RootCertData {
  // The SHA-256 hash of the associated certificate's subjectPublicKeyInfo.
  unsigned char sha256_spki_hash[32];

  // A value suitable for histograms using the NetTrustAnchors enum.
  int16_t histogram_id : 15;
} kRootCerts[] = {
"""

FOOTER = """\
};

}  // namespace

}  // namespace net

#endif  // BRAVE_NET_CERT_ROOT_CERT_LIST_GENERATED_H_
"""

PEM_RE = re.compile(
    r'-----BEGIN CERTIFICATE-----(.*?)-----END CERTIFICATE-----', re.S
)


def parse_trust_anchors(textproto: Path) -> dict[str, int]:
    """Returns {cert sha256 hex: crs_root_id} for top-level trust_anchors."""
    anchors: dict[str, int] = {}
    depth = 0
    in_anchor = False
    cert_hash: str | None = None
    for line in textproto.read_text().splitlines():
        line = line.split('#', 1)[0].strip()
        if not line:
            continue
        if depth == 0 and line == 'trust_anchors {':
            in_anchor = True
            cert_hash = None
        elif in_anchor and depth == 1:
            if m := re.fullmatch(r'sha256_hex:\s*"([0-9a-f]{64})"', line):
                cert_hash = m.group(1)
            elif m := re.fullmatch(r'crs_root_id:\s*(\d+)', line):
                if cert_hash is None:
                    raise ValueError('crs_root_id before sha256_hex')
                anchors[cert_hash] = int(m.group(1))
        depth += line.count('{') - line.count('}')
        if depth == 0 and in_anchor:
            if cert_hash is None or cert_hash not in anchors:
                raise ValueError(f'Incomplete trust_anchors entry: {cert_hash}')
            in_anchor = False
    return anchors


def _read_tlv(der: bytes, offset: int) -> tuple[int, int, int]:
    """Returns (tag, value offset, value end) for the DER TLV at offset."""
    tag = der[offset]
    length = der[offset + 1]
    offset += 2
    if length & 0x80:
        num_bytes = length & 0x7F
        length = int.from_bytes(der[offset : offset + num_bytes], 'big')
        offset += num_bytes
    return tag, offset, offset + length


def extract_spki(cert_der: bytes) -> bytes:
    _, tbs_offset, _ = _read_tlv(cert_der, 0)
    _, offset, tbs_end = _read_tlv(cert_der, tbs_offset)
    tag, _, end = _read_tlv(cert_der, offset)
    if tag == 0xA0:  # Optional explicit [0] version.
        offset = end
    # Skip serialNumber, signature, issuer, validity, subject.
    for _ in range(5):
        _, _, offset = _read_tlv(cert_der, offset)
    tag, _, end = _read_tlv(cert_der, offset)
    if tag != 0x30 or end > tbs_end:
        raise ValueError('Malformed subjectPublicKeyInfo')
    return cert_der[offset:end]


def crs_spki_ids(textproto: Path, certs: Path) -> dict[str, int]:
    """Returns {spki sha256 hex: crs_root_id} for every CRS trust anchor."""
    anchors = parse_trust_anchors(textproto)
    result: dict[str, int] = {}
    found: set[str] = set()
    for pem in PEM_RE.findall(certs.read_text()):
        der = base64.b64decode(''.join(pem.split()))
        cert_hash = hashlib.sha256(der).hexdigest()
        if cert_hash not in anchors:
            continue
        found.add(cert_hash)
        spki_hash = hashlib.sha256(extract_spki(der)).hexdigest()
        crs_id = anchors[cert_hash]
        result[spki_hash] = min(crs_id, result.get(spki_hash, crs_id))
    if missing := anchors.keys() - found:
        raise ValueError(f'No certificate for trust anchors: {sorted(missing)}')
    return result


def merge(root_stores: Path, textproto: Path, certs: Path) -> dict[str, int]:
    """Returns {spki sha256 hex: histogram id}, never dropping a legacy entry"""
    merged = {
        spki: int(data['id'])
        for spki, data in json.loads(root_stores.read_text())['spkis'].items()
    }
    for spki, crs_id in crs_spki_ids(textproto, certs).items():
        if spki in merged:
            continue
        histogram_id = CRS_HISTOGRAM_ID_BASE + crs_id
        if histogram_id > MAX_HISTOGRAM_ID:
            raise ValueError(f'crs_root_id {crs_id} overflows histogram_id')
        merged[spki] = histogram_id
    return merged


def render(merged: dict[str, int]) -> str:
    rows = []
    for spki, histogram_id in sorted(merged.items()):
        hex_bytes = ', '.join(f'0x{b:02X}' for b in bytes.fromhex(spki))
        rows.append(f'    {{{{{hex_bytes}}}, {histogram_id}}},\n')
    return HEADER + ''.join(rows) + FOOTER


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root-stores', type=Path, required=True)
    parser.add_argument('--chrome-root-store', type=Path, required=True)
    parser.add_argument('--chrome-root-store-certs', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()

    merged = merge(
        args.root_stores, args.chrome_root_store, args.chrome_root_store_certs
    )
    args.output.write_text(render(merged))
    return 0


if __name__ == '__main__':
    sys.exit(main())
