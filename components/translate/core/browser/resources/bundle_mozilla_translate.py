def to_ascii(source: str) -> str:
    # TranslateAgent injects the script with WebString::FromAscii, which
    # DCHECKs that every byte is ASCII. Firefox comments contain box drawing.
    return source.encode("ascii", "replace").decode("ascii")


def strip_document(source: str) -> str:
    start = source.find(DOCUMENT_MARK)
    if start < 0:
        raise SystemExit("translations-document.sys.mjs is missing NodeStatus")
    body = source[start:]
    body = body.replace("export class ", "class ")
    return body


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit(
            "usage: bundle_mozilla_translate.py "
            "path/to/translations-document.sys.mjs")
    document = strip_document(pathlib.Path(sys.argv[1]).read_text())
    adapter = (HERE / "mozilla_translate_adapter.js").read_text()
    out = HERE / "mozilla_translate.js"
    out.write_text(to_ascii(SHIMS + document + "\n" + adapter))
    print(f"wrote {out} ({out.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
