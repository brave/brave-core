// Real mainnet v6 orchard->transparent transaction.
// https://3xpl.com/zcash/transaction/912abf1e9339aa7f1cd75fecf8ae92f0089fad0f559f55713363474fbe1f206a
TEST(OrchardBundleManagerTest, V6OrchardToTransparent) {
  OrchardBundleManager::OverrideRandomSeedForTesting(88345u);

  OrchardSpendsBundle spends_bundle;
  EXPECT_TRUE(PrefixedHexStringToFixed(
      base::StrCat({"0x", kV6OrchardToTransparentFvk}), spends_bundle.fvk));
  EXPECT_TRUE(PrefixedHexStringToFixed(
      base::StrCat({"0x", kV6OrchardToTransparentSk}), spends_bundle.sk));

  AddCapturedSpend(spends_bundle, kV6OrchardToTransparentSpend0Amount,
                   kV6OrchardToTransparentSpend0Addr,
                   kV6OrchardToTransparentSpend0Rho,
                   kV6OrchardToTransparentSpend0Seed,
                   kV6OrchardToTransparentSpend0WitnessPosition,
                   kV6OrchardToTransparentSpend0MerklePath);
  AddCapturedSpend(spends_bundle, kV6OrchardToTransparentSpend1Amount,
                   kV6OrchardToTransparentSpend1Addr,
                   kV6OrchardToTransparentSpend1Rho,
                   kV6OrchardToTransparentSpend1Seed,
                   kV6OrchardToTransparentSpend1WitnessPosition,
                   kV6OrchardToTransparentSpend1MerklePath);

  std::vector<OrchardOutput> outputs;
  OrchardOutput output;
  output.value = kV6OrchardToTransparentOutput0Value;
  EXPECT_TRUE(PrefixedHexStringToFixed(
      base::StrCat({"0x", kV6OrchardToTransparentOutput0Addr}), output.addr));
  outputs.push_back(std::move(output));

  auto state_tree_bytes = PrefixedHexStringToBytes(
      base::StrCat({"0x", kV6OrchardToTransparentTreeState}));
  ASSERT_TRUE(state_tree_bytes);

  auto orchard_bundle_manager = OrchardBundleManager::Create(
      *state_tree_bytes, std::move(spends_bundle), std::move(outputs),
      OrchardPool::kOrchard, /*is_v6_transaction=*/true);
  ASSERT_TRUE(orchard_bundle_manager);

  std::array<uint8_t, kZCashDigestSize> expected_digest;
  ASSERT_TRUE(PrefixedHexStringToFixed(
      base::StrCat({"0x", kV6OrchardToTransparentDigest}), expected_digest));
  auto digest = orchard_bundle_manager->GetOrchardDigest();
  ASSERT_TRUE(digest);
  EXPECT_EQ(ToHex(*digest), ToHex(expected_digest));

  std::array<uint8_t, kZCashDigestSize> sighash;
  ASSERT_TRUE(PrefixedHexStringToFixed(
      base::StrCat({"0x", kV6OrchardToTransparentSighash}), sighash));
  auto signed_manager = orchard_bundle_manager->ApplySignature(sighash);
  ASSERT_TRUE(signed_manager);
  auto orchard_raw_part = signed_manager->GetRawTxBytes();
  ASSERT_TRUE(orchard_raw_part);
  EXPECT_EQ(ToHex(*orchard_raw_part),
            base::StrCat({"0x", kV6OrchardToTransparentOrchardRawTx}));
}

