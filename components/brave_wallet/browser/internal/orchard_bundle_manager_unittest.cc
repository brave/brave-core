void AppendMerklePath(OrchardNoteWitness& witness, const std::string& hex) {
  OrchardMerkleHash hash;
  base::span(hash).copy_from(*PrefixedHexStringToBytes(hex));
  witness.merkle_path.push_back(hash);
}

void AppendMerklePathFromCapture(OrchardNoteWitness& witness,
                                 const char* hex_without_prefix) {
  AppendMerklePath(witness, base::StrCat({"0x", hex_without_prefix}));
}

void AddCapturedSpend(OrchardSpendsBundle& spends_bundle,
                      uint32_t amount,
                      const char* addr,
                      const char* rho,
                      const char* seed,
                      uint32_t witness_position,
                      base::span<const char* const> merkle_path) {
  OrchardInput input;
  input.note.amount = amount;
  EXPECT_TRUE(
      PrefixedHexStringToFixed(base::StrCat({"0x", addr}), input.note.addr));
  EXPECT_TRUE(
      PrefixedHexStringToFixed(base::StrCat({"0x", rho}), input.note.rho));
  EXPECT_TRUE(
      PrefixedHexStringToFixed(base::StrCat({"0x", seed}), input.note.seed));
  input.witness = OrchardNoteWitness();
  input.witness->position = witness_position;
  for (const char* merkle_hash : merkle_path) {
    AppendMerklePathFromCapture(input.witness.value(), merkle_hash);
  }
  spends_bundle.inputs.push_back(std::move(input));
}

